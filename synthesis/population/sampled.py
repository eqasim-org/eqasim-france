import numpy as np
import pandas as pd
import itertools

"""
This stage has the census data as input and samples households according to the
household weights given by INSEE. The resulting sample size can be controlled
through the 'sampling_rate' configuration option.

Two methods are available through the 'sampling_method' configuration option:

- random (default): the full population is generated by stochastic rounding of
  the household weights, then each household is kept with probability
  'sampling_rate'.

- stratified: households are sampled directly from the census by systematic
  sampling within each spatial stratum ('sampling_stratum', IRIS by default).
  Within a stratum, households are sorted by the criteria given in
  'sampling_criteria' (by order of priority). Each household is selected
  'weight * sampling_rate' times in expectation, as in the random method, but the
  number of sampled households in each stratum, and in each class of the first
  criterion within the stratum, matches the expected value up to one household.
  The following criteria are available (evaluated at the household level, the
  reference person being the oldest person in the household):

  - socioprofessional_class: class of the reference person
  - household_size: 1, 2, 3, 4, 5+
  - number_of_cars: 0, 1, 2+
  - age: age class of the reference person (<30, 30-44, 45-59, 60-74, 75+)
  - employed: number of employed persons in the household (0, 1, 2+)
  - housing_type: type of housing

In both cases, households are always sampled as a whole.
"""

SAMPLING_STRATA = ["iris", "commune", "departement"]
SAMPLING_CRITERIA = ["socioprofessional_class", "household_size", "number_of_cars", "age", "employed", "housing_type"]

def configure(context):
    if context.config("projection_year", None) is None:
        context.stage("data.census.filtered", alias = "source")
    else:
        context.stage("synthesis.population.projection.reweighted", alias = "source")

    context.config("random_seed")
    context.config("sampling_rate")

    context.config("sampling_method", "random")
    context.config("sampling_stratum", "iris")
    context.config("sampling_criteria", ["socioprofessional_class", "household_size"])

def get_household_criteria(df_census, criteria):
    # The reference person is the oldest person in the household
    df_reference = df_census.sort_values(by = ["household_id", "age"], ascending = [True, False])
    df_reference = df_reference.drop_duplicates("household_id").set_index("household_id")

    df_households = df_reference[["weight", "iris_id", "commune_id", "departement_id"]].reset_index()

    for criterion in criteria:
        if criterion == "socioprofessional_class":
            values = df_reference["socioprofessional_class"]
        elif criterion == "household_size":
            values = np.minimum(df_reference["household_size"], 5)
        elif criterion == "number_of_cars":
            values = np.minimum(df_reference["number_of_cars"], 2)
        elif criterion == "age":
            values = pd.Series(np.digitize(df_reference["age"], [30, 45, 60, 75]), index = df_reference.index)
        elif criterion == "employed":
            values = np.minimum(df_census.groupby("household_id")["employed"].sum(), 2)
        elif criterion == "housing_type":
            values = df_reference["housing_type"].cat.codes
        else:
            raise RuntimeError("Unknown sampling criterion: {} (available: {})".format(
                criterion, ", ".join(SAMPLING_CRITERIA)))

        df_households["criterion_" + criterion] = df_households["household_id"].map(values).values.astype(int)

    return df_households

def get_strata(df_households, stratum):
    # Use the requested spatial level, falling back to coarser levels when undefined
    strata = pd.Series("undefined", index = df_households.index)

    for level in SAMPLING_STRATA[SAMPLING_STRATA.index(stratum):]:
        values = df_households[level + "_id"].astype(str)
        f = (strata == "undefined") & (values != "undefined")
        strata[f] = level + ":" + values[f]

    return strata

def sample_stratified(df_census, sampling_rate, random, stratum = "iris", criteria = ["socioprofessional_class", "household_size"], serpentine = True):
    """
    Returns, for each census household, the number of times it is replicated in
    the sampled population.
    """
    if not stratum in SAMPLING_STRATA:
        raise RuntimeError("Unknown sampling stratum: {} (available: {})".format(
            stratum, ", ".join(SAMPLING_STRATA)))

    df_households = get_household_criteria(df_census, criteria)
    df_households["stratum"] = get_strata(df_households, stratum).astype("category").cat.codes.values

    # Sorting keys. With serpentine ordering, the order of a criterion is reversed
    # in every second class of the previous keys, so that consecutive households
    # in the sorted list stay as similar as possible
    keys = ["stratum"]

    for criterion in criteria:
        key = "criterion_" + criterion

        if serpentine:
            parity = df_households.groupby(keys, sort = True).ngroup().values % 2
            df_households[key] = np.where(parity == 1, -df_households[key], df_households[key])

        keys.append(key)

    df_households["tie_breaker"] = random.random(len(df_households))
    df_households = df_households.sort_values(by = keys + ["tie_breaker"])

    # Systematic sampling: one household every 1.0 on the cumulated expected
    # number of replications, starting from a random offset in each stratum
    expected = df_households["weight"].values * sampling_rate
    strata = df_households["stratum"].values

    cumulative = pd.Series(expected).groupby(strata).cumsum().values
    offset = random.random(strata.max() + 1)[strata]

    upper = np.floor(cumulative - offset)
    lower = np.floor(cumulative - expected - offset)

    df_households["multiplicator"] = (upper - lower).astype(int)
    return df_households[["household_id", "multiplicator"]]

def expand_households(df_census, df_multiplicators):
    # Replicate households given their multiplicator, keeping household members contiguous
    df_census = df_census.sort_values(by = ["household_id", "person_id"])

    household_ids, household_starts, household_sizes = np.unique(
        df_census["household_id"].values, return_index = True, return_counts = True)

    multiplicators = df_multiplicators.set_index("household_id")["multiplicator"].reindex(household_ids).values

    starts = np.repeat(household_starts, multiplicators)
    sizes = np.repeat(household_sizes, multiplicators)
    position = np.arange(np.sum(sizes)) - np.repeat(np.cumsum(sizes) - sizes, sizes)

    df_census = df_census.iloc[np.repeat(starts, sizes) + position].copy()

    # Create new household and person IDs
    df_census["census_person_id"] = df_census["person_id"]
    df_census["census_household_id"] = df_census["household_id"]

    df_census["person_id"] = np.arange(len(df_census))
    df_census["household_id"] = np.repeat(np.arange(len(sizes)), sizes)

    return df_census

def execute(context):
    df_census = context.stage("source").sort_values(by = ["household_id", "person_id"]).copy()

    sampling_rate = context.config("sampling_rate")
    random = np.random.default_rng(context.config("random_seed"))

    sampling_method = context.config("sampling_method")

    if sampling_method == "stratified":
        df_multiplicators = sample_stratified(df_census, sampling_rate, random,
            context.config("sampling_stratum"), context.config("sampling_criteria"))

        df_census = expand_households(df_census, df_multiplicators)

        del df_census["weight"]
        return df_census

    elif sampling_method != "random":
        raise RuntimeError("Unknown sampling method: {} (available: random, stratified)".format(sampling_method))

    # Perform stochastic rounding for the population (and scale weights)
    df_rounding = df_census[["household_id", "weight", "household_size"]].drop_duplicates("household_id")
    df_rounding["multiplicator"] = np.floor(df_rounding["weight"])
    df_rounding["multiplicator"] += random.random(len(df_rounding)) <= (df_rounding["weight"] - df_rounding["multiplicator"])
    df_rounding["multiplicator"] = df_rounding["multiplicator"].astype(int)

    # Multiply households (use same multiplicator for all household members)
    household_multiplicators = df_rounding["multiplicator"].values
    household_sizes = df_rounding["household_size"].values

    # create index to replicate all households members by their household weight
    # the order ([0, 1, 0, 1, 2, 2, ...]) is important here as they will be reassigned to new housholds later with that assumption
    expandor = np.split(np.arange(len(df_census)), np.cumsum(household_sizes))
    expandor = np.asarray([x for x in expandor if x.size > 0], dtype="object")
    expandor = np.repeat(expandor, household_multiplicators, axis=0)
    expandor = list(itertools.chain(*expandor))

    df_census = df_census.iloc[expandor]

    # Create new household and person IDs
    df_census["census_person_id"] = df_census["person_id"]
    df_census["census_household_id"] = df_census["household_id"]

    df_census["person_id"] = np.arange(len(df_census))

    household_sizes = np.repeat(household_sizes, household_multiplicators)
    household_count = np.sum(household_multiplicators)
    df_census.loc[:, "household_id"] = np.repeat(np.arange(household_count), household_sizes)

    # Select sample from 100% population
    selector = random.random(household_count) < sampling_rate
    selector = np.repeat(selector, household_sizes)
    df_census = df_census[selector]

    del df_census["weight"]
    return df_census
